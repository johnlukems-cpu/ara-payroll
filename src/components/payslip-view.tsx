import type { Company, Payslip, PayslipLine, PayrollRun } from "@prisma/client";
import { amount, date, money, periodLabel } from "@/lib/format";

type Slip = Payslip & { lines: PayslipLine[]; run: PayrollRun & { company: Company } };

export function PayslipView({ slip }: { slip: Slip }) {
  const c = slip.run.company;
  const earnings = slip.lines.filter((l) => l.type === "EARNING");
  const deductions = slip.lines.filter((l) => l.type === "DEDUCTION");
  const employer = slip.lines.filter((l) => l.type === "EMPLOYER");
  return (
    <article className="print-sheet mx-auto max-w-3xl rounded-xl border bg-white p-8 shadow-sm">
      <header className="flex flex-wrap items-start justify-between gap-4 border-b pb-6">
        <div>
          <p className="text-lg font-semibold">{c.legalName ?? c.name}</p>
          <p className="text-sm text-muted-foreground">{[c.address, c.district].filter(Boolean).join(", ")}</p>
          {c.taxNumber && <p className="text-xs text-muted-foreground">Tax no. {c.taxNumber}{c.kkfNumber ? ` · KKF ${c.kkfNumber}` : ""}</p>}
        </div>
        <div className="text-right">
          <p className="text-xs uppercase tracking-[0.14em] text-muted-foreground">Payslip</p>
          <p className="text-lg font-semibold">{periodLabel(slip.run.year, slip.run.month)}</p>
          <p className="text-sm text-muted-foreground">Pay date {date(slip.run.payDate)}</p>
        </div>
      </header>
      <section className="grid grid-cols-2 gap-4 border-b py-5 text-sm sm:grid-cols-4">
        <div><p className="text-muted-foreground">Employee</p><p className="font-medium">{slip.employeeName}</p></div>
        <div><p className="text-muted-foreground">Employee no.</p><p className="font-medium">{slip.employeeNumber}</p></div>
        <div><p className="text-muted-foreground">Position</p><p className="font-medium">{slip.jobTitle ?? "—"}</p></div>
        <div><p className="text-muted-foreground">Bank account</p><p className="font-medium">{slip.bankAccount ?? "—"}</p></div>
      </section>
      <section className="grid gap-8 py-5 sm:grid-cols-2">
        <LineTable title="Earnings" lines={earnings} total={slip.grossPay} totalLabel="Gross pay" />
        <LineTable title="Deductions" lines={deductions} total={slip.totalDeductions} totalLabel="Total deductions" />
      </section>
      <section className="flex items-center justify-between rounded-lg bg-primary px-5 py-4 text-primary-foreground">
        <span className="text-sm uppercase tracking-wide">Net pay</span>
        <span className="tabular text-2xl font-semibold">{money(slip.netPay, c.currency)}</span>
      </section>
      <section className="mt-5 grid grid-cols-2 gap-4 text-xs text-muted-foreground sm:grid-cols-4">
        <div>Taxable wage<br /><span className="tabular font-medium text-foreground">{amount(slip.taxableWage)}</span></div>
        <div>Wage tax<br /><span className="tabular font-medium text-foreground">{amount(slip.wageTax)}</span></div>
        <div>AOV<br /><span className="tabular font-medium text-foreground">{amount(slip.aov)}</span></div>
        {employer.map((l) => <div key={l.id}>{l.description}<br /><span className="tabular font-medium text-foreground">{amount(l.amount)}</span></div>)}
      </section>
      <footer className="mt-8 border-t pt-4 text-center text-[11px] text-muted-foreground">
        Generated by ARA Payroll · Developed by ARA Intelligent Solutions
      </footer>
    </article>
  );
}

function LineTable({ title, lines, total, totalLabel }: { title: string; lines: PayslipLine[]; total: number; totalLabel: string }) {
  return (
    <div>
      <p className="mb-2 text-xs font-semibold uppercase tracking-wide text-muted-foreground">{title}</p>
      <table className="w-full text-sm">
        <tbody>
          {lines.map((l) => (
            <tr key={l.id} className="border-b border-dashed last:border-0">
              <td className="py-1.5 pr-2">{l.description}{l.quantity != null && <span className="text-xs text-muted-foreground"> × {l.quantity}</span>}</td>
              <td className="tabular py-1.5 text-right">{amount(l.amount)}</td>
            </tr>
          ))}
          {lines.length === 0 && <tr><td className="py-1.5 text-muted-foreground">—</td></tr>}
        </tbody>
        <tfoot>
          <tr className="border-t font-semibold"><td className="pt-2">{totalLabel}</td><td className="tabular pt-2 text-right">{amount(total)}</td></tr>
        </tfoot>
      </table>
    </div>
  );
}
